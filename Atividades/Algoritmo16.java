public class Algoritmo16 {
    // Crie um algoritmo que mostre os números pares de 0 a 200. Use While
    public void main() {
        int i = 1;
        while (i <= 200) {
            if(i % 2 == 0) {
                System.out.println(i);
                
            }
            i++;

        }
    }
    
}
